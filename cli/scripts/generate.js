/**
 * Generates src/operations.generated.js from the server's OpenAPI document.
 * Run after changing server/openapi.json: `npm run generate`.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const specPath = path.join(here, '..', '..', 'server', 'openapi.json');
const outPath = path.join(here, '..', 'src', 'operations.generated.js');

const METHODS = ['get', 'put', 'post', 'delete', 'patch'];

/**
 * Turn an OpenAPI document into the operation table the CLI dispatches on.
 * @param {object} spec
 * @returns {object[]}
 */
export function operationsFromSpec(spec) {
  const ops = [];
  for (const [route, item] of Object.entries(spec.paths || {})) {
    for (const method of METHODS) {
      const op = item[method];
      if (!op) continue;
      if (!op.operationId) throw new Error(`${method.toUpperCase()} ${route} has no operationId`);
      const bearer = (op.security ?? spec.security ?? []).some((s) => 'bearerAuth' in s);
      const body = op.requestBody
        ? Object.keys(op.requestBody.content || {})[0] || null
        : null;
      ops.push({
        operationId: op.operationId,
        method: method.toUpperCase(),
        path: route,
        summary: op.summary || '',
        bearer,
        body,
        parameters: (op.parameters || []).map((p) => ({ name: p.name, in: p.in, required: !!p.required })),
      });
    }
  }
  return ops;
}

function render(ops) {
  return [
    '// Generated by scripts/generate.js from server/openapi.json. Do not edit by hand.',
    `export const operations = ${JSON.stringify(ops, null, 2)};`,
    '',
  ].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const spec = JSON.parse(fs.readFileSync(specPath, 'utf8'));
  fs.writeFileSync(outPath, render(operationsFromSpec(spec)));
  console.log(`wrote ${path.relative(process.cwd(), outPath)}`);
}
